#!/bin/bash
# ANNA keep-awake wrapper (L1 ранг 3). Держит ноут бодрым, пока супервизор жив, и
# запускает сам супервизор. caffeinate -i = не спать по простою; -m = не спать диску;
# -s = не спать системе (работает на ПИТАНИИ от сети). На батарее по закрытию крышки
# ноут всё равно уснёт — это честное ограничение ноута, не кода (настоящий фикс = always-on хост).
cd "$(dirname "$0")/.." || exit 1
exec caffeinate -ims python3 scripts/anna_supervisor_v1.py
