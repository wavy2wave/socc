def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--commit", action="store_true",
                    help="РЕАЛЬНАЯ запись наружу (без него — dry-эхо payload'ов, 0₽)")
    ap.add_argument("--only", choices=("prices", "stocks"), default=None)
    args = ap.parse_args()

    if args.commit and not hands.creds_present():
        print("НЕТ YANDEX_MARKET_API_KEY — живой коммит невозможен, честный отказ (не выдумываем).")
        sys.exit(2)

    mode = "ЖИВЬЁМ (commit)" if args.commit else "DRY (0₽, наружу ничего)"
    print(f"ТОРГОВЫЕ РУКИ · кабинет {BID} · склад {WH} · {mode}\n")

    # ── Шаг 1: цены комплектов 2/3шт +800 ───────────────────────────────
    if args.only in (None, "prices"):
        offers = [{"sku": s, "value": new} for s, old, new in REPRICE]
        print(f"[1] ЦЕНЫ комплектов 2шт/3шт: {len(offers)} SKU → +800₽")
        for s, old, new in REPRICE:
            print(f"      {s}  {old:>7.0f}₽ → {new:>7.0f}₽")
        r = T.update_prices(BID, offers, dry=not args.commit, commit=args.commit)
        if r.get("sent"):
            print(f"    итог: ok={r.get('ok')} count={r.get('count')} "
                  f"errors={r.get('errors') or '—'} warnings={r.get('warnings') or '—'}")
        else:
            print(f"    dry-эхо: {r.get('status')} (payload напечатан выше в функции)")
        print()

    # ── Шаг 2: остатки комплектам + плёнке ──────────────────────────────
    if args.only in (None, "stocks"):
        items = [{"sku": s, "warehouse_id": WH, "count": c} for s, c in STOCKS]
        n_set = sum(1 for s, _ in STOCKS if s.startswith("ARB2-"))
        n_film = sum(1 for s, _ in STOCKS if s.startswith("ARB-"))
        print(f"[2] ОСТАТКИ: {n_set} комплектов ×13 + {n_film} плёнки ARB-* ×100 "
              f"(итого {len(items)} позиций)")
        r = T.update_stocks(BID, items, dry=not args.commit, commit=args.commit)
        if r.get("sent"):
            print(f"    итог: ok={r.get('ok')} count={r.get('count')} "
                  f"errors={r.get('errors') or '—'} warnings={r.get('warnings') or '—'}")
        else:
            print(f"    dry-эхо: {r.get('status')}")

    print("\nГотово. SETTLE (~70–110 c) потом живая СВЕРКА чтением: status PUBLISHED/FIT + новая цена.")


if __name__ == "__main__":
    main()
