def _fmt_ru(x):
    """100.0→'100', 0.75→'0,75', 1.438→'1,438' — русская десятичная запятая для описания."""
    return f"{x:g}".replace(".", ",")


def _слои_слово(n):
    """2→'двухслойное', 3→'трёхслойное' (согласование с «полотно»)."""
    return {1: "однослойное", 2: "двухслойное", 3: "трёхслойное", 4: "четырёхслойное"}[n]


def _ген(x):
    """Имя прилагательное → родительный падеж (муж. род): «прозрачный»→«прозрачного»."""
    for suf, add in (("ий", "его"), ("ый", "ого"), ("ой", "ого")):
        if x.endswith(suf):
            return x[: -len(suf)] + add
    return x


