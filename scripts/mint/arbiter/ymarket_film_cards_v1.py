def _pub_urls_by_pid():
    """published_urls.json → {sku: [url,...]}. Пусто → честно пусто (карточка без фото)."""
    if not PUB_URLS_PATH.exists():
        return {}
    try:
        out = {}
        for e in json.loads(PUB_URLS_PATH.read_text()):
            u = e.get("urls") or []
            if u:
                out[str(e.get("sku"))] = u
        return out
    except Exception:
        return {}


