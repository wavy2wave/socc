def resolve_markup(markup):
    """Множитель цены из манифеста магазина → (число>1, ошибка_или_None).

    None (поле в манифесте не задано) → модульная MARKUP (8.0) — обратносовместимо, поведение
    как до проводки #13. Задано → ОБЯЗАНО быть числом > 1: JSON true/0/пустая строка/не-число/
    ≤1 — это БИТЫЙ манифест, а не воля оператора. Раньше `float(markup) if markup else MARKUP`
    тихо превращало true в 1.0, а 0/""/отсутствие — в 8.0 (маскировка коррупции), и цена уходила
    ≤ закупки (гарантированный убыток после издержек, P1) или молча «по дефолту». Ошибку НЕ
    глотаем — возвращаем причину, вызывающий (движок/билдер) решает: FAIL, а не тихая цена.
    """
    if markup is None:
        return MARKUP, None
    if isinstance(markup, bool):                  # bool→float: True==1.0 → цена == закупка
        return None, f"markup манифеста — boolean {markup!r}, не число (цена была бы ≤ закупки)"
    if isinstance(markup, str):
        s = markup.strip()
        if not s:
            return None, "markup манифеста — пустая строка (битый манифест)"
        try:
            markup = float(s)
        except ValueError:
            return None, f"markup манифеста «{markup}» — не число (битый манифест)"
    try:
        mult = float(markup)
    except (TypeError, ValueError):
        return None, f"markup манифеста «{markup!r}» — не число (битый манифест)"
    if mult <= 1.0:
        return None, (f"markup {mult:g} ≤ 1 — цена продажи {mult:g}× закупки ≤ закупки, "
                      "гарантированный убыток после издержек (P1); поставь > 1 (для плёнки ×8)")
    return mult, None


def build_product(p, pub_urls, index, *, markup=None):
    """Донор-строка → product-словарь ARBITER (схема ymarket_card.to_offer).

    markup=None → модульная константа MARKUP (8.0, подтверждена оператором 2026-09-02);
    markup=число → множитель МАНИФЕСТА магазина (профиль.markup — проводка: цена по манифесту,
    владелец ЦЕНОВИК, L9). Ровно тот же результат при markup==MARKUP (обратносовместимо).
    Битый markup (boolean/не-число/≤1) — НЕ тихая цена: ValueError с причиной (движок гейтит
    манифест до сборки своим FAIL-ом, тут — страховка для прямых вызовов билдера).
    """
    pid = str(p.get("pid") or p.get("sku"))
    article = str(p.get("article") or "")
    cost = float(p.get("cost") or 0)
    name = str(p.get("name") or "").strip()
    if not article or not name or cost <= 0:
        return None
    ean = gen_ean13(article)
    mult, merr = resolve_markup(markup)
    if merr:
        raise ValueError(merr)                # битый markup манифеста → громко, не тихая цена
    lo, _hi = C.propose_prices(cost, mult, mult)
    facts = FILM_FACTS.get(pid)
    prod = {
        "sku": f"ARB-{ean[-8:]}",        # СВОЙ артикул продавца (уникален в кабинете)
        "name": name,                     # имя донора 1-в-1 (без потерь размера)
        "barcode": ean,                   # СВОЙ EAN-13 — главный рычаг анти-склейки
        "cost": cost,                     # закупка у донора (₽)
        "price": round(lo),               # цена продажи: закупка ×markup (манифест/константа, L9)
        "article": article,               # артикул донора (только след, НЕ уходит в offer)
        "house_brand": HOUSE_BRAND,       # суффикс уникальности имени
        # ОБЯЗАТЕЛЬНОЕ «Бренд» категории (решение оператора 2026-09-02): ставим НАШ бренд ATLAS EDGE,
        # НЕ «Без бренда» и НЕ донора. Своя марка + СВОЙ EAN-13 → анти-склейка с донором цела
        # (vendor-строка — это атрибут, связку делает штрихкод; свой EAN её рвёт).
        "vendor": HOUSE_BRAND,
        "send_vendor": True,               # дропшип-рецепт: своя марка + свой EAN-13 (доказано 4/4)
        "unique_name": True,              # имя 1-в-1 + суффикс ATLAS EDGE (анти-склейка)
        "extra_kw": None,
        "pictures": pub_urls.get(pid, []),  # фирменные кадры (публичные URL)
        "dims_source": p.get("dims_source"),
        "pid": pid,
    }
    # ПОЛНАЯ КАРТОЧКА (директива оператора «сделано идеально — это и есть артефакт»):
    # факты сняты с живых карточек донора → _spec (все характеристики в параметры категории) +
    # НАШЕ описание (создано на основе донора, НЕ копия) + страна производства.
    if facts:
        prod["_spec"] = _build_spec(facts)
        prod["description"] = _build_description(facts)
        prod["manufacturerCountries"] = ["RU"]
    # weightDimensions: ВСЕ четыре, иначе честно None (не выдумываем)
    keys = ("length", "width", "height", "weight")
    if all(p.get(k) and float(p.get(k)) > 0 for k in keys):
        prod["weightDimensions"] = {k: float(p[k]) for k in keys}
    return prod


def build_all(dry=True, commit=False):
    """Полный сухой/реальный ход: скан → 4 продукта → publish_card ×4. Сводка."""
    raw = load_film_products()
    pub = _pub_urls_by_pid()
    products = [build_product(p, pub, i) for i, p in enumerate(raw)]
    products = [pr for pr in products if pr]
    if len(products) != len(TARGET_PIDS):
        missing = TARGET_PIDS - {pr["pid"] for pr in products}
        print(f"⚠️  не хватает продуктов (скан/данные): {sorted(missing)}")
    out = []
    for pr in products:
        r = W.publish_card(pr, slug=SLUG, dry=dry, commit=commit, photo_urls=pr["pictures"])
        out.append({"pid": pr["pid"], "sku": pr["sku"], "ok": r.get("ok"),
                    "price": pr["price"], "cost": pr["cost"], "dims": pr.get("weightDimensions"),
                    "photos": len(pr["pictures"]), "name": pr["name"][:52],
                    "errors": (r.get("errors") or r.get("error") or None),
                    "need_mapping": r.get("need_mapping"), "category_id": r.get("category_id")})
    return {"dry": dry, "products": out}


